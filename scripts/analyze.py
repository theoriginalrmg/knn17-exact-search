"""Turns results/*.csv into results/summary.md + results/fig_*.png."""
import csv, os, statistics
from collections import defaultdict
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = os.path.join(os.path.dirname(__file__), "..", "results")
OURS, FAISS = "#2a78d6", "#eb6834"   # categorical slots 1 and 2
INK, MUTED, GRID = "#2b2b2b", "#6b6b6b", "#e6e6e6"
plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK,
                     "xtick.color": MUTED, "ytick.color": MUTED, "axes.spines.top": False,
                     "axes.spines.right": False, "axes.grid": True, "grid.color": GRID,
                     "grid.linewidth": 0.6})

def load(name):
    p = os.path.join(R, name)
    if not os.path.exists(p): return []
    with open(p) as f:
        rows = [r for r in csv.DictReader(f) if r.get("impl") in ("tiled", "faiss", "ref")]
    for r in rows:
        for c in ("nb", "nq", "d", "k", "threads"): r[c] = int(r[c])
        for c in ("preprocess_s", "median_s", "min_s", "std_s", "qps", "peak_delta_MiB", "working_KiB"):
            r[c] = float(r[c])
    return rows

def ms(s): return f"{s*1e3:.2f}"
out = ["# Results summary (auto-generated by scripts/analyze.py)\n"]

# ------------------------------------------------------------------ E1 ----
e1 = load("e1_batch.csv")
if e1:
    Ts = sorted({r["threads"] for r in e1})
    ncol = min(4, len(Ts)); nrow = -(-len(Ts) // ncol)
    fig, grid = plt.subplots(nrow, ncol, figsize=(4.2 * ncol, 3.2 * nrow), sharey=True, squeeze=False)
    axes = list(grid.flat)
    for ax in axes[len(Ts):]: ax.set_visible(False)
    for ax, T in zip(axes, Ts):
        for impl, col, lab in (("tiled", OURS, "ours (tiled)"), ("faiss", FAISS, "Faiss IndexFlatL2")):
            pts = sorted((r["nq"], r["median_s"] * 1e3) for r in e1 if r["impl"] == impl and r["threads"] == T)
            ax.plot(*zip(*pts), color=col, lw=2, marker="o", ms=5, label=lab)
            ax.annotate(lab, pts[-1], xytext=(4, 0), textcoords="offset points", color=INK, fontsize=8, va="center")
        ax.set_xscale("log", base=2); ax.set_yscale("log")
        ax.set_title(f"{T} thread{'s' if T > 1 else ''}", color=INK, fontsize=10, loc="left")
        ax.set_xlabel("query batch size nq")
    for row in grid: row[0].set_ylabel("batch latency (ms, median)")
    axes[0].legend(frameon=False, loc="upper left")
    fig.suptitle("E1 · latency vs batch size (uniform, nb=200k, d=128, k=10)", x=0.01, ha="left", color=INK, fontsize=10)
    fig.tight_layout(); fig.savefig(os.path.join(R, "fig_e1_latency.png"), dpi=160); plt.close(fig)

    out.append("## E1 — batch size × threads (uniform, nb=200k, d=128, k=10)\n")
    out.append("| T | nq | ours ms | Faiss ms | speedup vs Faiss | ours QPS | Faiss QPS | ours params | Faiss path | Faiss peak Δ MiB | ours working KiB | check ours / Faiss |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    idx = {(r["impl"], r["threads"], r["nq"]): r for r in e1}
    for T in Ts:
        for nq in sorted({r["nq"] for r in e1}):
            o, f = idx.get(("tiled", T, nq)), idx.get(("faiss", T, nq))
            if not (o and f): continue
            out.append(f"| {T} | {nq} | {ms(o['median_s'])} ± {ms(o['std_s'])} | {ms(f['median_s'])} ± {ms(f['std_s'])} | "
                       f"{f['median_s']/o['median_s']:.2f}× | {o['qps']:.0f} | {f['qps']:.0f} | {o['params']} | "
                       f"{f['params'].split('path=')[1]} | {f['peak_delta_MiB']:.2f} | {o['working_KiB']:.1f} | {o['check']} / {f['check']} |")
    # scaling
    out.append("\n**Scaling** (Tparallel(1)/Tparallel(p) and Tbest-seq/Tparallel(p); best-seq = fastest 1-thread run of either library)\n")
    out.append("| nq | p | ours self-speedup | ours vs best-seq | Faiss self-speedup |")
    out.append("|---|---|---|---|---|")
    for nq in sorted({r["nq"] for r in e1}):
        o1, f1 = idx.get(("tiled", 1, nq)), idx.get(("faiss", 1, nq))
        if not (o1 and f1): continue
        best = min(o1["median_s"], f1["median_s"])
        for T in Ts[1:]:
            op, fp = idx.get(("tiled", T, nq)), idx.get(("faiss", T, nq))
            if op and fp:
                out.append(f"| {nq} | {T} | {o1['median_s']/op['median_s']:.2f} | {best/op['median_s']:.2f} | {f1['median_s']/fp['median_s']:.2f} |")
    out.append("")

    # speedup vs threads, each library relative to its own 1-thread run
    if len(Ts) > 1 and 1 in Ts:
        fig, axes = plt.subplots(1, 3, figsize=(11.4, 3.4), sharey=True)
        for ax, nq in zip(axes, (1, 64, 4096)):
            ax.plot(Ts, Ts, color=MUTED, lw=1, ls="--", label="ideal (linear)")
            for impl, col, lab, mk in (("tiled", OURS, "ours (tiled)", "o"), ("faiss", FAISS, "Faiss IndexFlatL2", "s")):
                base = idx.get((impl, 1, nq))
                pts = [(T, base["median_s"] / idx[impl, T, nq]["median_s"]) for T in Ts if base and (impl, T, nq) in idx]
                if pts: ax.plot(*zip(*pts), color=col, lw=2, marker=mk, ms=5, label=lab)
            ax.set_xticks(Ts); ax.set_xlabel("threads"); ax.set_title(f"nq = {nq}", color=INK, fontsize=10, loc="left")
        axes[0].set_ylabel("speedup over own 1-thread time")
        axes[0].legend(frameon=False, loc="upper left")
        fig.suptitle("E1 · speedup vs threads (uniform, nb=200k, d=128, k=10)", x=0.01, ha="left", color=INK, fontsize=10)
        fig.tight_layout(); fig.savefig(os.path.join(R, "fig_e1_scaling.png"), dpi=160); plt.close(fig)

def pair_table(rows, title, key):
    if not rows: return
    out.append(f"## {title}\n")
    out.append("| config | nq | ours ms | Faiss ms | speedup | ours params | Faiss path | check ours / Faiss |")
    out.append("|---|---|---|---|---|---|---|---|")
    idx = {(r["impl"], r["label"], r["nq"]): r for r in rows}
    for lab in dict.fromkeys(r["label"] for r in rows):
        for nq in sorted({r["nq"] for r in rows if r["label"] == lab}):
            o, f = idx.get(("tiled", lab, nq)), idx.get(("faiss", lab, nq))
            if o and f:
                out.append(f"| {lab} | {nq} | {ms(o['median_s'])} | {ms(f['median_s'])} | {f['median_s']/o['median_s']:.2f}× | "
                           f"{o['params']} | {f['params'].split('path=')[1]} | {o['check']} / {f['check']} |")
    out.append("")

pair_table(load("e2_dim.csv"), "E2 — dimension (uniform, nb=100k, k=10, all threads)", "d")
pair_table(load("e3_k.csv"), "E3 — k (uniform, nb=200k, d=128, all threads)", "k")
pair_table(load("e4_family.csv"), "E4 — input families (nb=200k, d=128, k=10, all threads)", "fam")

# ------------------------------------------------------------------ E5 ----
e5 = load("e5_selector.csv")
if e5:
    out.append("## E5 — D3 selector ablation (uniform, nb=200k, d=128, k=10, all threads)\n")
    grid_S = sorted({int(r["params"].split("S=")[1].split()[0]) for r in e5 if r["label"] == "grid"})
    out.append(f"Grid: S ∈ {{{','.join(map(str, grid_S))}}} × tq ∈ {{4,16,64}} × tb ∈ {{256,2048,16384}} ({9 * len(grid_S)} configs per nq).\n")
    out.append("| nq | selector choice | selector ms | best grid ms (config) | worst grid ms | selector / best | S=1 best ms | S>1 best ms |")
    out.append("|---|---|---|---|---|---|---|---|")
    nqs = sorted({r["nq"] for r in e5}); xs, sel, best, worst = [], [], [], []
    for nq in nqs:
        a = [r for r in e5 if r["nq"] == nq and r["label"] == "auto"]
        g = [r for r in e5 if r["nq"] == nq and r["label"] == "grid"]
        if not a or not g: continue
        a = a[0]; b = min(g, key=lambda r: r["median_s"]); w = max(g, key=lambda r: r["median_s"])
        s1 = min((r["median_s"] for r in g if "S=1 " in r["params"]), default=float("nan"))
        sp = min((r["median_s"] for r in g if "S=1 " not in r["params"]), default=float("nan"))
        out.append(f"| {nq} | {a['params']} | {ms(a['median_s'])} | {ms(b['median_s'])} ({b['params'].split(' T=')[0]}) | "
                   f"{ms(w['median_s'])} | {a['median_s']/b['median_s']:.2f} | {ms(s1)} | {ms(sp)} |")
        xs.append(nq); sel.append(a["median_s"] / b["median_s"]); worst.append(w["median_s"] / b["median_s"])
    out.append("")
    fig, ax = plt.subplots(figsize=(5.2, 3.0))
    ax.plot(xs, worst, color=FAISS, lw=2, marker="o", ms=5, label="worst grid config")
    ax.plot(xs, sel, color=OURS, lw=2, marker="o", ms=5, label="selector's choice")
    ax.axhline(1, color=MUTED, lw=1, ls="--")
    ax.set_xscale("log", base=2); ax.set_xlabel("query batch size nq"); ax.set_ylabel("time / best grid time")
    ax.legend(frameon=False)
    ax.set_title("E5 · D3 selector vs exhaustive grid (1.0 = optimal)", loc="left", color=INK, fontsize=10)
    fig.tight_layout(); fig.savefig(os.path.join(R, "fig_e5_selector.png"), dpi=160); plt.close(fig)

e6 = load("e6_reference.csv")
if e6:
    out.append("## E6 — sequential double-precision reference (D1)\n")
    out.append("| nq | ms | ms / query |\n|---|---|---|")
    for r in e6: out.append(f"| {r['nq']} | {ms(r['median_s'])} | {ms(r['median_s']/r['nq'])} |")
    out.append("")

# ------------------------------------------------------------------ E7 ----
bwp = os.path.join(R, "e7_bandwidth.csv")
e7 = load("e7_scan.csv")
if e7 and os.path.exists(bwp):
    bw, sc = defaultdict(list), defaultdict(list)
    with open(bwp) as f:
        for r in csv.DictReader(f): bw[int(r["threads"]), int(r["MiB"])].append(float(r["median_GBs"]))
    for r in e7:  # bytes read per query: packed panels (16 rows each) + one norm per row
        gb = (r["nb"] + 15) // 16 * 16 * (r["d"] + 1) * 4 / 1e9
        sc[r["label"], r["threads"]].append(gb / r["median_s"])
    med, rng = statistics.median, lambda v: f"{min(v):.1f}–{max(v):.1f}"
    Ts = sorted({t for l, t in sc if l == "scan"})
    out.append("## E7 — memory bandwidth vs nq=1 scan rate (uniform, nb=200k, d=128, k=10)\n")
    out.append("Median of 5 rounds (range), GB/s = 10^9 bytes/s. Scan rate = packed database bytes (103.2 MB) / search time.\n")
    out.append("| T | read 1 GiB | read 99 MiB | our nq=1 scan | scan / read 1 GiB | scan / read 99 MiB |")
    out.append("|---|---|---|---|---|---|")
    for T in Ts:
        a, b, c = bw[T, 1024], bw[T, 99], sc["scan", T]
        out.append(f"| {T} | {med(a):.1f} ({rng(a)}) | {med(b):.1f} ({rng(b)}) | {med(c):.1f} ({rng(c)}) | "
                   f"{100*med(c)/med(a):.0f}% | {100*med(c)/med(b):.0f}% |")
    if sc["incache", 1]:
        c = sc["incache", 1]
        out.append(f"\nIn-cache scan (2000 rows, fits L2), 1 thread: {med(c):.1f} GB/s ({rng(c)}).")
    out.append("")
    fig, ax = plt.subplots(figsize=(5.2, 3.2))
    ax.plot(Ts, [med(bw[T, 1024]) for T in Ts], color=MUTED, lw=2, marker="^", ms=5, label="memory read, 1 GiB")
    ax.plot(Ts, [med(bw[T, 99]) for T in Ts], color=OURS, lw=2, marker="o", ms=5, label="memory read, 99 MiB")
    ax.plot(Ts, [med(sc["scan", T]) for T in Ts], color=FAISS, lw=2, marker="s", ms=5, label="our nq=1 scan")
    ax.set_xticks(Ts); ax.set_ylim(bottom=0); ax.set_xlabel("threads"); ax.set_ylabel("GB/s (median)")
    ax.legend(frameon=False, loc="lower right")
    ax.set_title("E7 · nq=1 scan rate vs memory read bandwidth", loc="left", color=INK, fontsize=10)
    fig.tight_layout(); fig.savefig(os.path.join(R, "fig_e7_bandwidth.png"), dpi=160); plt.close(fig)

open(os.path.join(R, "summary.md"), "w").write("\n".join(out))
print("\n".join(out))
